document.addEventListener('DOMContentLoaded', () => {
  localStorage.removeItem('theme'); // dark-only, no theme switching
  
  // Check if deep linking to Digital Electronics
  const hash = window.location.hash || '';
  const pathname = window.location.pathname || '';
  if (hash.includes('digital-electronics') || pathname.includes('digital-electronics')) {
    const dePath = findNodePath(DATA, 'Digital Electronics');
    if (dePath) {
      currentPath = dePath;
    }
  }

  renderHeroStats();
  renderFooterLastUpdated();
  render();
  updateRouteUrl();

  // Check if deep linking to a specific chapter in hash
  if (hash.includes('chapter-')) {
    const match = hash.match(/chapter-(\d+)/);
    if (match) {
      const chNum = parseInt(match[1], 10);
      const deNode = getNodeAtPath(currentPath);
      if (deNode && deNode.children) {
        const ch = deNode.children.find(c => c.number === chNum);
        if (ch && ch.url && ch.url !== '#') {
          setTimeout(() => openPdfModal(ch.url, ch.name), 400);
        }
      }
    }
  }
});


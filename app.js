function updateRouteUrl() {
  const node = getNodeAtPath(currentPath);
  if (node && (node.isSubjectView || node.name === 'Digital Electronics')) {
    if (window.location.hash !== '#/notes/btech/2nd-year/3rd-semester/digital-electronics/') {
      history.replaceState({ path: currentPath }, '', '#/notes/btech/2nd-year/3rd-semester/digital-electronics/');
    }
    document.title = 'Digital Electronics Notes | 3rd Semester | NotesArchived';
  } else {
    document.title = 'Students Archived - B.Tech Study Library';
    if (window.location.hash.startsWith('#/notes/btech/2nd-year/3rd-semester/digital-electronics/')) {
      history.replaceState({ path: currentPath }, '', window.location.pathname);
    }
  }
}

function findNodePath(root, targetName, cur = []) {
  if (root.name === targetName) return cur;
  if (!root.children) return null;
  for (let i = 0; i < root.children.length; i++) {
    const res = findNodePath(root.children[i], targetName, [...cur, i]);
    if (res) return res;
  }
  return null;
}


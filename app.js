// Recursively collect all files with path metadata
function getAllFiles(node = getActiveData(), pathNames = [], parentPathIdx = [], results = []) {
  if (!node || !node.children) return results;
  node.children.forEach((child, i) => {
    if (child.type === 'file') {
      results.push({
        file: child,
        fileIdx: i,
        parentPath: [...parentPathIdx],
        pathNames: [...pathNames],
      });
    } else if (child.type === 'folder') {
      getAllFiles(child, [...pathNames, child.name], [...parentPathIdx, i], results);
    }
  });
  return results;
}



// Handle search input
function handleSearch(value) {
  searchQuery = value.trim().toLowerCase();
  const clearBtn = document.getElementById('search-clear');
  if (clearBtn) clearBtn.style.display = searchQuery ? 'flex' : 'none';
  renderFileList();
}

// Clear search
function clearSearch() {
  const input = document.getElementById('search-input');
  if (input) input.value = '';
  handleSearch('');
}

/* 
   NAVIGATION
   */

function getNodeAtPath(path) {
  let node = getActiveData();
  for (const idx of path) {
    if (!node.children) return null;
    node = node.children[idx];
  }
  return node;
}

function navigateTo(path) {
  currentPath = [...path];
  render();
  updateRouteUrl();
  document.querySelector('.explorer-container').scrollIntoView({ behavior: 'smooth', block: 'start' });
}

function navigateUp() {
  if (currentPath.length > 0) {
    currentPath.pop();
    render();
  }
}

function navigateToIndex(idx) {
  const node = getNodeAtPath(currentPath);
  if (!node || !node.children) return;
  const child = node.children[idx];
  if (child.type === 'folder') {
    navigateTo([...currentPath, idx]);
  } else if (child.type === 'file') {
    if (child.url && child.url !== '#') {
      openPdfModal(child.url, child.name);
    } else {
      showToast('Note not linked yet ll Soon Uploaded');
    }
  }
}

function breadcrumbNavigateTo(path) {
  navigateTo(path);
}

